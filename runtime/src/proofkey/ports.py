"""Six provider-neutral surfaces. Dispatch acknowledgements never verify effects."""
from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from .contracts import AuthContext, AuthorityReadback, DispatchResult, EffectIntent, ReadRequest


class CasePort(Protocol):
    def read_case(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_principal(self, request: ReadRequest) -> AuthorityReadback: ...


class DeliveryPort(Protocol):
    def read_delivery(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_refusal(self, request: ReadRequest) -> AuthorityReadback: ...
    def register_goods_refusal(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...
    def register_service_refusal(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...


class SchedulingPort(Protocol):
    def list_permitted_slots(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_schedule(self, request: ReadRequest) -> AuthorityReadback: ...
    def reschedule(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...


class ReturnsPort(Protocol):
    def read_return_policy(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_return(self, request: ReadRequest) -> AuthorityReadback: ...
    def create_return(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...


class MessagingPort(Protocol):
    def read_message(self, request: ReadRequest) -> AuthorityReadback: ...
    def send_clarification(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...
    def send_status(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...


class OperatorPort(Protocol):
    def read_receipt(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_resume(self, request: ReadRequest) -> AuthorityReadback: ...
    def read_owner(self, request: ReadRequest) -> AuthorityReadback: ...
    def enqueue_handoff(self, intent: EffectIntent, *, deadline: datetime | None = None) -> DispatchResult: ...
    def transfer_owner(self, intent: EffectIntent, *, deadline: datetime | None = None,
                       auth: AuthContext | None = None) -> DispatchResult: ...


@dataclass(frozen=True)
class AdapterBundle:
    case: CasePort
    delivery: DeliveryPort
    scheduling: SchedulingPort
    returns: ReturnsPort
    messaging: MessagingPort
    operator: OperatorPort
