"""Explicitly migrated PostgreSQL case storage and fenced analysis intents.

Snapshots remain canonical TEXT generated by the shared v1 case implementation.
The outbox records intent only; no provider or external effect runs here.
"""
from contextlib import contextmanager
from contextvars import ContextVar
import logging
from pathlib import Path
import re
import uuid

import psycopg
from psycopg import sql
from psycopg.conninfo import conninfo_to_dict
from psycopg_pool import ConnectionPool, PoolClosed, PoolTimeout, TooManyRequests

from .cases import CaseError, CaseStore, _identifier


_SCHEMA = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,62}")
_JOB_ID = re.compile(r"[a-f0-9]{32}")
_DB_ERRORS = (psycopg.Error, PoolClosed, PoolTimeout, TooManyRequests, OSError,
              ValueError, TypeError, UnicodeError, RecursionError, OverflowError)
_PUBLIC_COLUMNS = "job_id, case_id, revision, snapshot_hash, status"
_POOL_NAME_PREFIX = "proofkey-db-"
_DATABASE_LOG_SCOPE = ContextVar("proofkey_database_log_scope", default=False)


class _PoolLogFilter(logging.Filter):
    """Redact only this service's database operations and named pool threads.

    Pool diagnostics can contain connection exceptions and connection reprs.
    Keep severity and occurrence, but never interpolate their payloads. The
    context covers caller-side rollback/close; names cover background workers
    even if they finish after the caller's scope has exited.
    """
    def filter(self, record):
        if _DATABASE_LOG_SCOPE.get() or record.threadName.startswith(_POOL_NAME_PREFIX):
            record.msg = "proofkey_database_pool_event"
            record.args = ()
            record.exc_info = record.exc_text = record.stack_info = None
            if hasattr(record, "message"):
                record.message = record.msg
        return True


_POOL_LOG_FILTER = _PoolLogFilter()
for _logger_name in ("psycopg", "psycopg.pool", "psycopg.transaction", "psycopg.waiting",
                     "psycopg.pq", "psycopg.debug", "psycopg_pool.sched"):
    logging.getLogger(_logger_name).addFilter(_POOL_LOG_FILTER)


@contextmanager
def _database_log_scope():
    token = _DATABASE_LOG_SCOPE.set(True)
    try:
        yield
    finally:
        _DATABASE_LOG_SCOPE.reset(token)


def _schema(value):
    if type(value) is not str or _SCHEMA.fullmatch(value) is None or value.lower().startswith("pg_"):
        raise ValueError("invalid_database_schema")
    return value


def _search_path(connection, schema):
    connection.execute(sql.SQL("SET LOCAL search_path TO {}, pg_catalog").format(sql.Identifier(schema)))


def migrate(database_url, *, schema="public"):
    """Apply the shipped versioned schema atomically; never create a database."""
    schema = _schema(schema)
    try:
        conninfo_to_dict(database_url)
        with _database_log_scope(), psycopg.connect(database_url, connect_timeout=10) as connection:
            connection.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))", ("proofkey:migrate:" + schema,))
            connection.execute(sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(sql.Identifier(schema)))
            _search_path(connection, schema)
            connection.execute("CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY, applied_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp())")
            rows = connection.execute("SELECT version FROM schema_migrations ORDER BY version").fetchall()
            if any(row[0] != 1 for row in rows):
                raise CaseError("case_storage_error")
            if not rows:
                migration = Path(__file__).with_name("migrations") / "001_case_backend.sql"
                connection.execute(migration.read_text(encoding="utf-8"))
                connection.execute("INSERT INTO schema_migrations(version) VALUES (1)")
    except CaseError:
        raise
    except _DB_ERRORS:
        raise CaseError("case_storage_error") from None


class _Row(dict):
    def __getitem__(self, key):
        return tuple(self.values())[key] if type(key) is int else super().__getitem__(key)


def _row_factory(cursor):
    names = [column.name for column in cursor.description] if cursor.description else []
    return lambda values: _Row(zip(names, values))


class _Connection:
    """Adapt only the shared CaseStore's parameter syntax and row contract."""
    def __init__(self, connection):
        self.connection = connection

    def execute(self, statement, parameters=()):
        return self.connection.execute(statement.replace("?", "%s"), parameters)


class PostgresCaseStore(CaseStore):
    def __init__(self, database_url, *, schema="public", min_size=0, max_size=4):
        self.schema = _schema(schema)
        if (type(min_size) is not int or type(max_size) is not int
                or not 1 <= max_size <= 128 or not 0 <= min_size <= max_size):
            raise ValueError("invalid_database_pool")
        self.pool = None
        try:
            # Reject malformed settings before worker threads can log them.
            conninfo_to_dict(database_url)
            with _database_log_scope():
                self.pool = ConnectionPool(database_url, min_size=min_size, max_size=max_size,
                                           name=_POOL_NAME_PREFIX + uuid.uuid4().hex,
                                           max_waiting=32, timeout=10, open=True,
                                           kwargs={"connect_timeout": 10, "row_factory": _row_factory})
            self.check_ready()
        except CaseError:
            self.close()
            raise
        except _DB_ERRORS:
            self.close()
            raise CaseError("case_storage_error") from None

    @contextmanager
    def _transaction(self, write=False):
        try:
            if self.pool is None:
                raise CaseError("case_storage_error")
            with _database_log_scope(), self.pool.connection() as connection:
                with connection.transaction():
                    if not write:
                        connection.execute("SET TRANSACTION ISOLATION LEVEL REPEATABLE READ READ ONLY")
                    _search_path(connection, self.schema)
                    if write:
                        connection.execute("SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))",
                                           ("proofkey:write:" + self.schema,))
                    yield _Connection(connection)
        except CaseError:
            raise
        except _DB_ERRORS:
            raise CaseError("case_storage_error") from None

    def check_ready(self):
        with self._transaction() as connection:
            row = connection.execute("SELECT version FROM schema_migrations ORDER BY version").fetchall()
            if len(row) != 1 or row[0][0] != 1:
                raise CaseError("case_storage_error")
            for table in ("case_heads", "case_snapshots", "case_requests", "analysis_outbox"):
                connection.execute("SELECT 1 FROM " + table + " LIMIT 0")

    def close(self):
        if self.pool is not None:
            with _database_log_scope():
                self.pool.close()
            self.pool = None

    def _after_revision(self, connection, snapshot):
        connection.execute("""INSERT INTO analysis_outbox (job_id, case_id, revision, snapshot_hash)
            VALUES (?, ?, ?, ?)""", (uuid.uuid4().hex, snapshot["case_id"], snapshot["revision"], snapshot["snapshot_hash"]))

    def analysis_jobs(self, case_id):
        _identifier(case_id)
        with self._transaction() as connection:
            history = self._history(connection, case_id)
            rows = connection.execute(
                "SELECT " + _PUBLIC_COLUMNS + " FROM analysis_outbox WHERE case_id=? ORDER BY revision",
                (case_id,)).fetchall()
            if len(rows) != len(history):
                raise CaseError("case_storage_error")
            for row, snapshot in zip(rows, history):
                self._validate_intent(row, snapshot)
            return [dict(row) for row in rows]

    @staticmethod
    def _validate_intent(row, snapshot):
        if (row["case_id"] != snapshot["case_id"] or row["revision"] != snapshot["revision"]
                or row["snapshot_hash"] != snapshot["snapshot_hash"]
                or type(row["job_id"]) is not str or _JOB_ID.fullmatch(row["job_id"]) is None
                or row["status"] not in ("pending", "leased", "completed")):
            raise CaseError("case_storage_error")

    def claim_analysis(self, worker_id, *, lease_seconds=60):
        _identifier(worker_id)
        if type(lease_seconds) is not int or not 1 <= lease_seconds <= 3600:
            raise CaseError("invalid_case_request")
        token = uuid.uuid4().hex
        with self._transaction(write=True) as connection:
            row = connection.execute("""WITH candidate AS (
                SELECT job_id FROM analysis_outbox
                WHERE status='pending' OR (status='leased' AND lease_expires_at <= clock_timestamp())
                ORDER BY created_at, job_id FOR UPDATE SKIP LOCKED LIMIT 1)
                UPDATE analysis_outbox AS jobs SET status='leased', lease_token=?, worker_id=?,
                    lease_expires_at=clock_timestamp() + (? * interval '1 second')
                FROM candidate WHERE jobs.job_id=candidate.job_id
                RETURNING jobs.job_id, jobs.case_id, jobs.revision, jobs.snapshot_hash, jobs.status,
                    jobs.lease_token, jobs.lease_expires_at""", (token, worker_id, lease_seconds)).fetchone()
            if row is None:
                return None
            history = self._history(connection, row["case_id"])
            revision = row["revision"]
            if not 0 <= revision < len(history):
                raise CaseError("case_storage_error")
            self._validate_intent(row, history[revision])
            result = dict(row)
            result["lease_expires_at"] = result["lease_expires_at"].isoformat()
            return result

    def ack_analysis(self, job_id, lease_token):
        if (type(job_id) is not str or _JOB_ID.fullmatch(job_id) is None
                or type(lease_token) is not str or _JOB_ID.fullmatch(lease_token) is None):
            return False
        with self._transaction(write=True) as connection:
            row = connection.execute("""UPDATE analysis_outbox SET status='completed',
                lease_token=NULL, worker_id=NULL, lease_expires_at=NULL
                WHERE job_id=? AND status='leased' AND lease_token=?
                    AND lease_expires_at > clock_timestamp() RETURNING job_id""", (job_id, lease_token)).fetchone()
            return row is not None
